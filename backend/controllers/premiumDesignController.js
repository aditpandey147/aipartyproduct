// backend/src/controllers/premiumDesignController.js
const fs = require("fs/promises");
const path = require("path");
const axios = require("axios");
const aiService = require("../services/aiService");

// ================================================================
// STORAGE
// ================================================================
const UPLOAD_ROOT = path.join(__dirname, "..", "uploads", "premium-designs");

// ================================================================
// STYLE HINTS
// ================================================================
const STYLE_HINTS = {
  luxury:   "elegant gold foil accents, refined serif typography, rich jewel tones",
  vintage:  "retro 1950s aesthetic, soft muted colors, ornate flourishes",
  modern:   "clean minimal layout, bold sans-serif, high contrast, geometric",
  cute:     "playful pastel colors, rounded shapes, kid-friendly illustrations",
  elegant:  "soft florals, delicate script fonts, refined pastel palette",
  festive:  "vibrant holiday colors, confetti, glitter, celebratory energy",
  minimal:  "lots of white space, single accent color, thin lines, geometric simplicity",
  bohemian: "earthy tones, hand-drawn elements, natural textures, wanderlust vibe",
};

// ================================================================
// Helpers
// ================================================================
function buildFullPrompt({ prompt, styleTags }) {
  const styleHints = styleTags
    .map((id) => STYLE_HINTS[id])
    .filter(Boolean)
    .join(", ");

  return [
    prompt.trim(),
    styleHints && `Style: ${styleHints}.`,
    "Professional party design, print-ready, high resolution, no watermark, flat 2D poster layout.",
  ]
    .filter(Boolean)
    .join(" ");
}

async function saveImageLocally(replicateUrl, userId) {
  await fs.mkdir(UPLOAD_ROOT, { recursive: true });

  const res = await axios.get(replicateUrl, {
    responseType: "arraybuffer",
    timeout: 60_000,
  });

  const filename = `${userId}-${Date.now()}.png`;
  const localPath = path.join(UPLOAD_ROOT, filename);
  await fs.writeFile(localPath, Buffer.from(res.data));

  return {
    url: `/uploads/premium-designs/${filename}`,
    localPath,
    sizeBytes: res.data.byteLength || res.data.length,
  };
}

// ================================================================
// POST /api/premium-design/generate
// ================================================================
exports.generate = async (req, res) => {
  const startedAt = Date.now();
  try {
    const userId = req.user?.id || req.user?._id;
    if (!userId) {
      return res.status(401).json({ success: false, message: "Unauthorized" });
    }

    const {
      prompt,
      ratio = "5:7",
      sdxlRatio = "portrait",
      styleTags = [],
      designStyle = "Modern",
    } = req.body;

    if (!prompt || !prompt.trim()) {
      return res.status(400).json({ success: false, message: "prompt is required" });
    }

    // 1. Build prompt
    const fullPrompt = buildFullPrompt({ prompt, styleTags });

    // 2. Replicate → temporary URL
    const replicateUrl = await aiService.image({
      prompt: fullPrompt,
      aspectRatio: sdxlRatio,   // "portrait" | "wide" | "square"
      steps: 30,
      guidance: 7.5,
    });

    if (!replicateUrl) {
      throw new Error("No image generated by AI provider");
    }

    // 3. Save locally (permanent)
    let finalUrl = replicateUrl;
    let savedLocally = false;

    try {
      const stored = await saveImageLocally(replicateUrl, userId);
      finalUrl = stored.url;
      savedLocally = true;
    } catch (saveErr) {
      console.warn("Could not persist image locally, using Replicate URL:", saveErr.message);
    }

    // 4. Respond
    return res.json({
      success: true,
      data: {
        url: finalUrl,
        prompt: fullPrompt,
        ratio,
        sdxlRatio,
        styleTags,
        designStyle,
        savedLocally,
        durationMs: Date.now() - startedAt,
      },
    });
  } catch (err) {
    console.error("premium-design generate error:", err);
    return res.status(500).json({
      success: false,
      message: err.message || "Generation failed",
    });
  }
};

