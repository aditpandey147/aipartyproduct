// ================================================================
// POST /api/premium-design/polish
// Takes a rough user prompt and returns a polished version via DeepSeek.
// ================================================================
exports.polish = async (req, res) => {
  try {
    const { prompt, styleTags = [] } = req.body;

    if (!prompt || !prompt.trim()) {
      return res.status(400).json({ success: false, message: "prompt is required" });
    }

    const styleHints = styleTags
      .map((id) => STYLE_HINTS[id])
      .filter(Boolean)
      .join(", ");

    const systemPrompt = `
You are an expert party-design prompt engineer for AI image generators.
Your job: take a rough user description and rewrite it into a vivid, specific,
print-ready image prompt for a party design (invitations, decor, signage, etc.).

Rules:
- Output ONLY the improved prompt text. No labels, no quotes, no preamble.
- Keep it 60–120 words.
- Include: subject, layout, colors, typography hints, mood, style.
- Mention "print-ready", "high resolution", "no watermark", "flat 2D poster layout".
- Do not invent personal data the user didn't provide.
- Preserve the user's intent — improve clarity, don't change the concept.
`.trim();

    const userMessage = `
Original user description:
"${prompt.trim()}"

${styleHints ? `Preferred style hints: ${styleHints}` : ""}

Rewrite this into a single polished AI image prompt.
`.trim();

    const polished = await aiService.chat({
      systemPrompt,
      userMessage,
      temperature: 0.7,
      maxTokens: 400,
    });

    const cleaned = (polished || "")
      .replace(/^["'`]+|["'`]+$/g, "")
      .trim();

    if (!cleaned || cleaned.length < 20) {
      throw new Error("Could not polish prompt");
    }

    return res.json({
      success: true,
      data: { prompt: cleaned },
    });
  } catch (err) {
    console.error("premium-design polish error:", err);
    return res.status(500).json({
      success: false,
      message: err.message || "Failed to polish prompt",
    });
  }
};